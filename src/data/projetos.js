const TIPOS_JOGO = ['Roguelike', 'Tabuleiro', 'RPG', '3D RPG', 'Tower Defense', 'Card Game']
const TIPOS_WEB = ['Web App', 'App']
const TIPOS_ESTUDO = ['Bot', 'Estudo']

export const naCategoria = (projeto, categoria) => {
  if (categoria === 'todos') return true
  if (categoria === 'jogos') return TIPOS_JOGO.includes(projeto.tipo)
  if (categoria === 'web') return TIPOS_WEB.includes(projeto.tipo)
  if (categoria === 'estudo') return TIPOS_ESTUDO.includes(projeto.tipo)
  return true
}

